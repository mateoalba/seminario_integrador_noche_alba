# Ingreso de datos del vuelo
pasajeros_vuelo1 = float(input("Ingrese pasajeros del vuelo 1: "))
pasajeros_vuelo2 = float(input("Ingrese pasajeros del vuelo 2: "))

print("=== OPERACIONES DEL SISTEMA DE VUELOS ===")

print("Suma de pasajeros")
print(f"{pasajeros_vuelo1} + {pasajeros_vuelo2} = {pasajeros_vuelo1 + pasajeros_vuelo2}")

print("Diferencia de pasajeros")
print(f"{pasajeros_vuelo1} - {pasajeros_vuelo2} = {pasajeros_vuelo1 - pasajeros_vuelo2}")

print("Multiplicación")
print(f"{pasajeros_vuelo1} * {pasajeros_vuelo2} = {pasajeros_vuelo1 * pasajeros_vuelo2}")

print("Promedio de pasajeros")
print(f"{pasajeros_vuelo1} / {pasajeros_vuelo2} = {pasajeros_vuelo1 / pasajeros_vuelo2}")

print("Módulo")
print(f"{pasajeros_vuelo1} % {pasajeros_vuelo2} = {pasajeros_vuelo1 % pasajeros_vuelo2}")

print("Exponente")
print(f"{pasajeros_vuelo1} ** {pasajeros_vuelo2} = {pasajeros_vuelo1 ** pasajeros_vuelo2}")