print("===== OPERADORES DE COMPARACIÓN - CONTROL DE VUELOS =====")

altitud_vuelo1 = float(input("Ingrese la altitud del primer vuelo: "))
altitud_vuelo2 = float(input("Ingrese la altitud del segundo vuelo: "))

print(altitud_vuelo1, "==", altitud_vuelo2, ":", altitud_vuelo1 == altitud_vuelo2)
print(altitud_vuelo1, "!=", altitud_vuelo2, ":", altitud_vuelo1 != altitud_vuelo2)
print(altitud_vuelo1, ">", altitud_vuelo2, ":", altitud_vuelo1 > altitud_vuelo2)
print(altitud_vuelo1, "<", altitud_vuelo2, ":", altitud_vuelo1 < altitud_vuelo2)
print(altitud_vuelo1, ">=", altitud_vuelo2, ":", altitud_vuelo1 >= altitud_vuelo2)
print(altitud_vuelo1, "<=", altitud_vuelo2, ":", altitud_vuelo1 <= altitud_vuelo2)